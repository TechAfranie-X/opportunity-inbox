#!/usr/bin/env python3
"""Rebuilds lib/identity/wd-logos.generated.ts from the files present in public/brands/wd (file stem = normalized company key). Safe to run at any time."""
import json, os, re
root = os.path.join(os.path.dirname(__file__), "../..")
d = os.path.join(root, "public/brands/wd")
kept = {}
for f in sorted(os.listdir(d)):
    stem = os.path.splitext(f)[0]
    kept[stem] = f
    base = re.sub(r"(university|college|instituteoftechnology)$", "", stem)
    if len(base) >= 4 and base != stem: kept.setdefault(base, f)
open(os.path.join(root, "lib/identity/wd-logos.generated.ts"), "w").write("/* GENERATED by scripts/identity/wd-manifest.py (pack built by build-logo-pack.py from public Wikidata + Wikimedia Commons; public-domain / CC0 files only). key -> file in public/brands/wd. Do not edit. */\nexport const WD_LOGOS: Record<string, string> = " + json.dumps(kept, separators=(",", ":")) + ";\n")
print(len(kept), "keys from", len(os.listdir(d)), "files")
