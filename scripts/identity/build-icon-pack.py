#!/usr/bin/env python3
"""
Developer tool, run once: turns the Simple Icons package (CC0) into one SVG file per brand with its official colour baked in, plus a small index.
Usage: build-icon-pack.py <extracted package dir containing icons/ and _data/simple-icons.json>
Output: public/brands/si/<slug>.svg and lib/identity/si-index.generated.ts ({ key: [slug, hex] }); keys are normalized name forms and the slug.
Nothing is fetched and nothing about any user is involved.
"""
import json, os, re, sys
pkg = sys.argv[1]
root = os.path.join(os.path.dirname(__file__), "../..")
out = os.path.join(root, "public/brands/si"); os.makedirs(out, exist_ok=True)
SUF = re.compile(r"\b(incorporated|inc|llc|ltd|limited|corp|corporation|co|company|plc|gmbh|ag|sa|nv|holdings?|group|technologies|technology|the)\b\.?", re.I)
def flat(s): return re.sub(r"[^a-z0-9]", "", s.lower().replace("&", "and"))
def core(s): return flat(SUF.sub(" ", s)) or flat(s)
data = json.load(open(os.path.join(pkg, "_data/simple-icons.json")))
icons = data["icons"] if isinstance(data, dict) else data
index = {}; n = 0
for i in icons:
    slug = i.get("slug") or re.sub(r"[^a-z0-9]", "", i["title"].lower().replace("+", "plus").replace(".", "dot").replace("&", "and"))
    src = os.path.join(pkg, "icons", slug + ".svg")
    if not os.path.exists(src): continue
    m = re.search(r'<path d="([^"]+)"', open(src).read())
    if not m: continue
    open(os.path.join(out, slug + ".svg"), "w").write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="#{i["hex"]}"><path d="{m.group(1)}"/></svg>')
    n += 1
    for k in {core(i["title"]), flat(i["title"]), slug}:
        if k and k not in index: index[k] = [slug, i["hex"]]
open(os.path.join(root, "lib/identity/si-index.generated.ts"), "w").write("/* GENERATED by scripts/identity/build-icon-pack.py from Simple Icons 14.15.0 (CC0). key -> [file slug in public/brands/si, official hex colour]. Do not edit. */\nexport const SI_INDEX: Record<string, [string, string]> = " + json.dumps(index, separators=(",", ":")) + ";\n")
print(n, "icons,", len(index), "keys")
