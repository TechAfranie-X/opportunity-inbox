#!/usr/bin/env python3
"""
Builds lib/identity/seed.generated.ts from PUBLIC Wikidata (CC0). Run once by a developer; the product never calls Wikidata.
No private data is involved: the queries below are fixed and contain nothing about any user.
Inputs: JSON result files from these SPARQL queries (query.wikidata.org), saved as *.json in the directory given (public, business, company, software):
  public:   SELECT ?c ?cLabel ?site ?parent ?parentLabel WHERE { ?c wdt:P31 wd:Q891723 . ?c wdt:P856 ?site . OPTIONAL { ?c wdt:P749 ?parent } SERVICE wikibase:label { bd:serviceParam wikibase:language "en". } } LIMIT 8000
  business: same, with ?c wdt:P31 wd:Q4830453 . ?c wdt:P1128 ?e . FILTER(?e > 1000)
  company:  same, with ?c wdt:P31 wd:Q783794 and ?c wdt:P571 ?inc FILTER(?inc > 1985-01-01), LIMIT 15000
  software: same, with ?c wdt:P31 wd:Q1058914 (software company), LIMIT 6000
Usage: build-seed.py <dir> [<dir> ...] [--merge-existing]   (--merge-existing keeps rows already in the generated file)
"""
import json, os, re, sys
from urllib.parse import urlparse

dirs = [a for a in sys.argv[1:] if a != "--merge-existing"]
merge_existing = "--merge-existing" in sys.argv
words = set()
try:
    words = {w.strip().lower() for w in open('/usr/share/dict/words') if w.strip().islower()}
except OSError:
    pass

SECOND = {'co', 'com', 'org', 'net', 'gov', 'ac', 'edu'}
def registrable(url):
    h = (urlparse(url).hostname or '').lower()
    h = re.sub(r'^www\d?\.', '', h)
    p = h.split('.')
    if len(p) >= 3 and p[-2] in SECOND and len(p[-1]) == 2: return '.'.join(p[-3:])
    return '.'.join(p[-2:]) if len(p) >= 2 else ''

orgs = {}
for f in [os.path.join(d, x) for d in dirs for x in sorted(os.listdir(d)) if x.endswith('.json')]:
    for b in json.load(open(f))['results']['bindings']:
        qid = b['c']['value'].rsplit('/', 1)[-1]
        name = b['cLabel']['value'].strip()
        if re.match(r'^Q\d+$', name) or not name or len(name) > 48: continue
        o = orgs.setdefault(qid, {'name': name, 'domains': set(), 'parent': None})
        dom = registrable(b['site']['value'])
        if dom: o['domains'].add(dom)
        if 'parentLabel' in b and not re.match(r'^Q\d+$', b['parentLabel']['value']): o['parent'] = b['parentLabel']['value']

rows = []
existing = {}
if merge_existing:
    prev = open(os.path.join(os.path.dirname(__file__), '../../lib/identity/seed.generated.ts')).read()
    for r in json.loads(prev[prev.index('= ') + 2:prev.rindex(';')]): existing[r[0]] = r
for qid, o in orgs.items():
    if not o['domains']: continue
    flat = re.sub(r'[^a-z0-9]', '', o['name'].lower())
    first = re.sub(r'[^a-z]', '', o['name'].lower().split()[0]) if o['name'].split() else ''
    amb = 1 if (len(flat) <= 3 or (' ' not in o['name'].strip() and flat in words) or (first in words and len(o['name'].split()) == 1)) else 0
    row = [o['name'], sorted(o['domains'])[:4], o['parent'] or '', amb]
    if o['name'] in existing:
        old = existing.pop(o['name']); row[1] = sorted(set(old[1]) | set(row[1]))[:4]; row[2] = row[2] or old[2]; row[3] = max(row[3], old[3])
    rows.append(row)
rows.extend(existing.values())
rows.sort(key=lambda r: r[0].lower())
out = '/* GENERATED by scripts/identity/build-seed.py from public Wikidata (CC0). [name, domains, parent, ambiguous]. Do not edit by hand. */\nexport const WIKIDATA_ORGS: Array<[string, string[], string, number]> = ' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(os.path.join(os.path.dirname(__file__), '../../lib/identity/seed.generated.ts'), 'w').write(out)
print(len(rows), 'orgs', len(out) // 1024, 'KB', sum(r[3] for r in rows), 'ambiguous')
