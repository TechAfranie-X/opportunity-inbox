/**
 * Side-by-side comparison of the product's current decision chain and the shadow evidence-ledger engine, on IDENTICAL cached model readings.
 *
 *   node --no-warnings --import ./scripts/loader/register.mjs scripts/eval-compare.ts [--out eval/compare-phase1.md]
 *
 * Reports pooled and per-fixture metrics for both engines next to the frozen baseline and the pre-regression reference, the messages on which the two engines disagree (with who was
 * right), the calibration of the shadow engine's belief, the precision of its "verified" and "proposed" endings, and a traceable explanation for sample decisions.
 * Development fixtures only: their failures have been inspected, so this is a regression and design comparison, NOT a generalisation estimate.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { FIXTURES, LOWER_IS_BETTER, metricsOf, pool, type Baseline, type Metrics } from "./eval-gate.ts";

type PerMessage = { scenario: string; id: string; expectInPipeline: boolean; expectType: string | null; gotType: string | null; state: string | null; placement: string | null; terminal: string | null; belief: number | null; verdict: { reasons: string[]; for: string[]; against: string[]; type: string | null; typeFor: string[]; typeAgainst: string[] } | null };
type Run = { counts: Record<string, number>; perMessage: PerMessage[] };

const arg = (n: string) => (process.argv.includes(n) ? process.argv[process.argv.indexOf(n) + 1] : null);
const root = process.cwd();
const tmp = mkdtempSync(join(tmpdir(), "eval-compare-"));
function run(f: string, engine: string): Run {
  const out = join(tmp, `${f}-${engine}.json`);
  execFileSync(process.execPath, ["--no-warnings", "--import", "./scripts/loader/register.mjs", "scripts/eval-journeys.ts", `eval/dev/journeys-${f}.json`, "--semantic", "--replay", "--cache", `eval/dev/cache-${f}.json`, "--engine", engine, "--json", out], { cwd: root, stdio: ["ignore", "ignore", "ignore"] });
  return JSON.parse(readFileSync(out, "utf8")) as Run;
}
const cur: Record<string, Run> = {}, sha: Record<string, Run> = {};
for (const f of FIXTURES) { cur[f] = run(f, "current"); sha[f] = run(f, "shadow"); }
const baseline = JSON.parse(readFileSync("eval/baseline.json", "utf8")) as Baseline;
const reference = JSON.parse(readFileSync("eval/reference-8ee0e95.json", "utf8")) as Baseline;
const pc = metricsOf(pool(Object.fromEntries(FIXTURES.map((f) => [f, cur[f].counts]))));
const ps = metricsOf(pool(Object.fromEntries(FIXTURES.map((f) => [f, sha[f].counts]))));

const L: string[] = [];
const fmt = (n: number) => (Number.isInteger(n) ? String(n) : n.toFixed(1));
const arrow = (k: string, a: number, b: number) => { const d = Math.round((b - a) * 10) / 10; if (d === 0) return "="; const good = LOWER_IS_BETTER.has(k) ? d < 0 : d > 0; return `${d > 0 ? "+" : ""}${fmt(d)} ${good ? "better" : "worse"}`; };
L.push("# Phase 1 comparison: current pipeline vs shadow decision engine (identical cached readings)\n");
L.push("Generated by `scripts/eval-compare.ts`. Fixtures: development set J, K, L, M, N (contaminated: failures inspected) and X (adversarial: confidently wrong model readings, authored from known failure modes by the engine's author). This is a regression and design comparison, not a generalisation estimate; fresh fixture O is reserved for release validation.\n");
L.push("## 1. Pooled metrics\n");
L.push("| metric | reference 8ee0e95 | baseline (current, frozen) | current (now) | shadow engine | shadow vs current |\n|---|---|---|---|---|---|");
for (const k of Object.keys(pc)) L.push(`| ${k} | ${fmt(reference.pooled[k])} | ${fmt(baseline.pooled[k])} | ${fmt(pc[k])} | ${fmt(ps[k])} | ${arrow(k, pc[k], ps[k])} |`);

L.push("\n## 2. Per fixture (recall / status / outcome / false opportunities / wrong merges)\n");
L.push("| fixture | current | shadow |\n|---|---|---|");
for (const f of FIXTURES) { const a = metricsOf(cur[f].counts), b = metricsOf(sha[f].counts); const s = (m: Metrics) => `${fmt(m.recruitingRecall)} / ${fmt(m.statusAccuracy)} / ${fmt(m.outcomeAccuracy)} / ${m.falseOpportunities} / ${m.wrongMerges}`; L.push(`| ${f} | ${s(a)} | ${s(b)} |`); }

// message-level disagreement
let agree = 0; const dis = { shadowRight: 0, currentRight: 0, bothWrong: 0, onlyShadowFound: 0, onlyCurrentFound: 0, shadowTypeRight: 0, currentTypeRight: 0 };
const byKind: Record<string, number> = {};
for (const f of FIXTURES) {
  const cm = new Map(cur[f].perMessage.map((m) => [`${m.scenario}/${m.id}`, m]));
  for (const s of sha[f].perMessage) {
    const c = cm.get(`${s.scenario}/${s.id}`)!;
    const inC = c.gotType !== null, inS = s.gotType !== null;
    if (inC === inS && c.gotType === s.gotType) { agree++; continue; }
    const truth = s.expectInPipeline;
    const okC = truth ? inC && (!s.expectType || c.gotType === s.expectType) : !inC;
    const okS = truth ? inS && (!s.expectType || s.gotType === s.expectType) : !inS;
    if (okS && !okC) dis.shadowRight++; else if (okC && !okS) dis.currentRight++; else dis.bothWrong++;
    const kind = `${truth ? "real" : "not-recruiting"}: current=${c.gotType ?? "absent"} shadow=${s.gotType ?? "absent"}${okS && !okC ? " (shadow right)" : okC && !okS ? " (current right)" : " (both wrong)"}`;
    byKind[kind] = (byKind[kind] ?? 0) + 1;
  }
}
L.push("\n## 3. Message-level disagreements\n");
L.push(`Messages where the two engines produce the same pipeline type: **${agree}**. Where they differ: shadow right **${dis.shadowRight}**, current right **${dis.currentRight}**, both wrong **${dis.bothWrong}**.\n`);
L.push("| disagreement | messages |\n|---|---|");
for (const [k, n] of Object.entries(byKind).sort((a, b) => b[1] - a[1])) L.push(`| ${k} | ${n} |`);

// calibration + terminal precision
const all = FIXTURES.flatMap((f) => sha[f].perMessage).filter((m) => m.belief !== null);
const bins: [string, (b: number) => boolean][] = [["belief < 0.35 (noise)", (b) => b < 0.35], ["0.35 to 0.8 (possible)", (b) => b >= 0.35 && b < 0.8], ["0.8 to 0.95", (b) => b >= 0.8 && b < 0.95], [">= 0.95", (b) => b >= 0.95]];
L.push("\n## 4. Calibration of the shadow engine's belief (share of messages that really are in the pipeline)\n");
L.push("| belief | messages | really recruiting |\n|---|---|---|");
for (const [name, fn] of bins) { const xs = all.filter((m) => fn(m.belief!)); L.push(`| ${name} | ${xs.length} | ${xs.length ? `${((xs.filter((m) => m.expectInPipeline).length / xs.length) * 100).toFixed(0)}%` : "n/a"} |`); }
L.push("\n## 5. Endings: verified vs proposed (messages the engine marked as a rejection or withdrawal)\n");
L.push("| terminal state | messages | really that ending |\n|---|---|---|");
for (const t of ["verified", "proposed"]) { const xs = all.filter((m) => m.terminal === t); const ok = xs.filter((m) => m.expectInPipeline && (m.expectType === "rejection" || m.expectType === "withdrawn")).length; L.push(`| ${t} | ${xs.length} | ${xs.length ? `${ok}/${xs.length} (${((ok / xs.length) * 100).toFixed(0)}%)` : "n/a"} |`); }
const states: Record<string, number> = {}; for (const m of all) states[m.state ?? "none"] = (states[m.state ?? "none"] ?? 0) + 1;
L.push(`\nVerdict states over ${all.length} messages with evidence: ${Object.entries(states).map(([k, n]) => `${k} ${n}`).join(", ")}.`);

// traceability sample from the adversarial fixture
L.push("\n## 6. Traceable decisions (fixture X, invented mail)\n");
L.push("Every verdict lists the claims it leaned on (`for`) and weighed against (`against`), written `source:kind=value` (rule = deterministic reader, model = verified local model, fact = a yes/no property of the text, person = the owner).\n");
const label = (id: string) => { const p = id.split("."); return `${p[0]}:${p[2]}=${p.slice(3).join(".")}`; };
L.push("| message | state / placement / ending | for | against |\n|---|---|---|---|");
for (const m of sha.X.perMessage.filter((x) => x.verdict)) L.push(`| ${m.id} (really ${m.expectInPipeline ? m.expectType : "not recruiting"}) | ${m.state} / ${m.placement} / ${m.terminal} | ${m.verdict!.for.map(label).join(", ") || "-"} | ${m.verdict!.against.map(label).join(", ") || "-"} |`);
const outPath = arg("--out");
if (outPath) { writeFileSync(outPath, `${L.join("\n")}\n`); console.log(`written ${outPath}`); } else console.log(L.join("\n"));
